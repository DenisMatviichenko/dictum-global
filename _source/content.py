def parse(fname):
    pages, cur, card = [], None, None
    for raw in open(os.path.join(HERE, fname), encoding='utf-8'):
        line = raw.rstrip('\n')
        if not line.strip():
            continue
        if line.startswith('#') and not line.startswith('##'):
            slug, title = line[1:].split('|', 1)
            cur = {'slug': slug.strip(), 'title': title.strip(), 'intro': [], 'cards': [], 'adv': []}
            pages.append(cur); card = None
        elif line.startswith('## '):
            card = {'t': line[3:].strip(), 'li': []}
            cur['cards'].append(card)
        elif line.startswith('- '):
            item = line[2:].strip()
            if item not in card['li']:
                card['li'].append(item)
        elif line.startswith('P '):
            cur['intro'].append(line[2:].strip())
        elif line.startswith('A '):
            t, d = line[2:].split('|', 1)
            cur['adv'].append((t.strip(), d.strip()))
        elif line.startswith('C '):
            for t in line[2:].split(' / '):
                cur['cards'].append({'t': t.strip(), 'li': []})
    return pages

